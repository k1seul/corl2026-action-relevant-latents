"""Write COMMON_DECODER.md — three-backbone common frozen decoder result.

Reads final training MSE/LPIPS/PSNR from TensorBoard event files and pairs
with the audited frozen action R² for correlation.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

from tensorboard.backend.event_processing.event_accumulator import EventAccumulator

REPO_ROOT = Path(__file__).resolve().parents[2]
CKPT_ROOT = REPO_ROOT / "runs/corl2026_rebuttal/checkpoints"
MC_JSONL = REPO_ROOT / "runs/corl2026_rebuttal/results/matched_controls.jsonl"
FINAL_JSONL = REPO_ROOT / "runs/corl2026_rebuttal/results/wave1_finalized_stats.jsonl"
OUT_MD = REPO_ROOT / "runs/corl2026_rebuttal/reports/COMMON_DECODER.md"
OUT_JSONL = REPO_ROOT / "runs/corl2026_rebuttal/results/common_decoder_frozen.jsonl"


def read_last_metrics(tb_dir: Path, tail_n: int = 5) -> dict:
    """Read TB scalars and return step-sorted summaries.

    Single-batch loss can bounce by ±3 dB per log window, so we report the
    mean over the last ``tail_n`` logged steps rather than the very last point.
    """
    ea = EventAccumulator(str(tb_dir), size_guidance={"scalars": 0}); ea.Reload()
    tags = ea.Tags()["scalars"]
    out = {}
    for t in tags:
        evts = sorted(ea.Scalars(t), key=lambda e: e.step)
        if not evts: continue
        tail = evts[-tail_n:]
        out[t] = {
            "last": evts[-1].value,
            "last_step": evts[-1].step,
            "first": evts[0].value,
            "first_step": evts[0].step,
            "tail_mean": statistics.mean(e.value for e in tail),
            "tail_min":  min(e.value for e in tail),
            "tail_max":  max(e.value for e in tail),
            "tail_steps": [e.step for e in tail],
            "n": len(evts),
        }
    return out


def frozen_action_r2(backbone: str) -> float | None:
    """Look up audited pooled frozen R² (mean over 3 probe seeds)."""
    if not FINAL_JSONL.exists():
        return None
    rows = [json.loads(l) for l in FINAL_JSONL.open() if l.strip()]
    for r in rows:
        if r.get("kind") == "cell" and r["backbone"] == backbone and r["condition"] == "frozen":
            return r["pooled_r2_probe_mean"]
    return None


def pearson_spearman(xs, ys):
    """Return (pearson, spearman). Pure Python for stdlib safety."""
    n = len(xs)
    if n < 2: return None, None
    mx = sum(xs) / n; my = sum(ys) / n
    num = sum((a - mx) * (b - my) for a, b in zip(xs, ys))
    dx = (sum((a - mx) ** 2 for a in xs)) ** 0.5
    dy = (sum((b - my) ** 2 for b in ys)) ** 0.5
    pearson = num / (dx * dy) if dx * dy > 1e-12 else None

    # Spearman: rank both, then Pearson of ranks
    def _rank(vals):
        s = sorted(range(len(vals)), key=lambda i: vals[i])
        r = [0.0] * len(vals)
        for i, k in enumerate(s):
            r[k] = i + 1
        return r
    rx = _rank(xs); ry = _rank(ys)
    mrx = sum(rx) / n; mry = sum(ry) / n
    num = sum((a - mrx) * (b - mry) for a, b in zip(rx, ry))
    dx = (sum((a - mrx) ** 2 for a in rx)) ** 0.5
    dy = (sum((b - mry) ** 2 for b in ry)) ** 0.5
    spearman = num / (dx * dy) if dx * dy > 1e-12 else None
    return pearson, spearman


def main():
    entries = []
    for bb in ["vjepa2", "videomae", "webdino"]:
        tb_dir = CKPT_ROOT / f"decoder_{bb}_frozen" / "tb"
        if not tb_dir.exists():
            continue
        m = read_last_metrics(tb_dir, tail_n=5)
        entry = {
            "backbone": bb,
            "final_step": m.get("train/mse", {}).get("last_step"),
            "train_mse": m.get("train/mse", {}).get("tail_mean"),
            "train_lpips": m.get("train/lpips", {}).get("tail_mean"),
            "train_psnr_db": m.get("train/psnr", {}).get("tail_mean"),
            "train_mse_last": m.get("train/mse", {}).get("last"),
            "train_psnr_last": m.get("train/psnr", {}).get("last"),
            "train_psnr_min5": m.get("train/psnr", {}).get("tail_min"),
            "train_psnr_max5": m.get("train/psnr", {}).get("tail_max"),
            "tail_steps": m.get("train/psnr", {}).get("tail_steps"),
            "action_r2_frozen_pooled": frozen_action_r2(bb),
        }
        entries.append(entry)

    with OUT_JSONL.open("w") as f:
        for e in entries:
            f.write(json.dumps(e) + "\n")

    lines = ["# COMMON_DECODER.md — three-backbone common frozen decoder\n\n"]
    lines.append("Generated by `scripts/rebuttal/write_common_decoder_report.py`.\n\n")
    lines.append("## Protocol\n\n")
    lines.append("* Encoder: frozen public backbone (V-JEPA2 ViT-L / VideoMAE ViT-L / Web-DINO 300M).\n")
    lines.append("* Decoder: identical `PixelDecoder` (`src/comparison/decoders/pixel_decoder.py`) "
                 "with `latent_dim = encoder.feat_dim` → linear projection to (256, 8, 8) "
                 "tile → 4× ConvTranspose2d to 128×128 RGB. ~17M decoder params.\n")
    lines.append("* Loss: MSE + 0.1 × LPIPS(AlexNet).\n")
    lines.append("* Optimizer: AdamW lr=1e-4, wd=0.01, 500-step warmup, 10 000 total steps.\n")
    lines.append("* Data: LIBERO-taskheld train split, agentview_rgb, 128×128, "
                 "batch=2 (V-JEPA2) / batch=4 (VideoMAE, Web-DINO), num_workers=0.\n\n")

    lines.append("## Final metrics (mean over last 5 log points ≈ last ~1000 steps)\n\n")
    lines.append("Single-batch loss can bounce by ±3 dB per log window; the values below "
                 "are the mean over the last 5 logged steps so a single noisy mini-batch "
                 "doesn't dominate the summary. `last_step` is the most recent step logged.\n\n")
    lines.append("| Backbone | MSE (tail-mean) | LPIPS (tail-mean) | PSNR dB (tail-mean [min–max]) | last_step | Audited frozen action R² |\n")
    lines.append("|----------|-----------------|---------------------|-------------------------------|-----------|---------------------------|\n")
    for e in entries:
        step_note = "" if e["final_step"] and e["final_step"] >= 9800 else " ⚠️ still running"
        lines.append(
            f"| {e['backbone']} | {e['train_mse']:.4f} | {e['train_lpips']:.4f} | "
            f"{e['train_psnr_db']:.2f} [{e['train_psnr_min5']:.2f}–{e['train_psnr_max5']:.2f}] | "
            f"{e['final_step']}{step_note} | "
            f"{e['action_r2_frozen_pooled']:+.4f} |\n"
        )

    # correlations
    complete = [e for e in entries if e["train_psnr_db"] is not None and e["action_r2_frozen_pooled"] is not None]
    if len(complete) >= 2:
        psnrs = [e["train_psnr_db"] for e in complete]
        r2s   = [e["action_r2_frozen_pooled"] for e in complete]
        mses  = [e["train_mse"] for e in complete]
        lpips = [e["train_lpips"] for e in complete]
        p_psnr, s_psnr = pearson_spearman(psnrs, r2s)
        p_mse,  s_mse  = pearson_spearman(mses, r2s)
        p_lp,   s_lp   = pearson_spearman(lpips, r2s)
        lines.append("\n## Correlation with frozen action R² (audited, l2 probe, 26 tasks)\n\n")
        lines.append(f"* Pearson ρ(PSNR, action R²) = {p_psnr:+.4f} — n={len(complete)}\n")
        lines.append(f"* Spearman ρ(PSNR, action R²) = {s_psnr:+.4f}\n")
        lines.append(f"* Pearson ρ(MSE, action R²) = {p_mse:+.4f}\n")
        lines.append(f"* Spearman ρ(MSE, action R²) = {s_mse:+.4f}\n")
        lines.append(f"* Pearson ρ(LPIPS, action R²) = {p_lp:+.4f}\n")
        lines.append(f"* Spearman ρ(LPIPS, action R²) = {s_lp:+.4f}\n\n")

    lines.append("## Scope caveat (per instruction P5)\n\n")
    lines.append("This is explicitly labelled a **three-backbone sensitivity analysis**. "
                 "It compares the trained decoder's train-set MSE/LPIPS/PSNR under a "
                 "single identical decoder protocol. It does NOT repair the submitted "
                 "cross-family Figure 1 (which reports test-set values across "
                 "SigLIP2/LAPA/SDXL VAE/Cosmos and other backbones we haven't run here).\n\n")
    lines.append("Also note: reported PSNR/MSE/LPIPS are **training-set metrics**. "
                 "Since the encoder is frozen and the decoder is small (17M) with "
                 "10k steps on 4160 clips × 32 frames, train and test are expected to "
                 "be close, but a strict test-OOD decoder evaluation would be needed "
                 "to publish these values as final. That eval is a fast follow-up "
                 "(one pass over test_ood clips with the trained decoder).\n")

    OUT_MD.write_text("".join(lines))
    print(f"wrote {OUT_JSONL}\nwrote {OUT_MD}")


if __name__ == "__main__":
    main()
