"""Camera-ready CAIP table (fills the "CAIP text-conditioned: TODO").

Reads ``runs/corl2026_rebuttal/tables/caip_exact_protocol.csv`` (written by
``scripts/rebuttal/caip_exact_protocol.py``; protocol in
``runs/corl2026_rebuttal/reports/CAIP_EXACT_PROTOCOL.md``) and writes a LaTeX
table. The text-conditioned row receives task text, so it is set apart from the
vision-only rows, as the rebuttal promised.

Protocol of every number in the table: frozen features, MLP probe
D→256→128→7, AdamW lr 3e-4, wd 1e-4, batch 512, 3000 steps, no feature
normalisation, 3 probe seeds, probe-train = first 400 episodes of the submitted
train split. "200 ep" = first 200 test-OOD episodes (the Table 1 test pool);
"26 tasks" = all 1300 test-OOD episodes with a 10k-replicate task-cluster
bootstrap 95% CI.

Outputs go to ``runs/camera_ready/caip/``.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

# figures/ layout (adapted from the 2026-10-06 handoff; only these paths changed)
FIG_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = FIG_ROOT.parent
SRC = FIG_ROOT / "data/caip_exact_protocol.csv"
OUT_DIR = FIG_ROOT / "out/tables"

LABELS = {
    "caip_visual_only": "CAIP ViT-L, visual only",
    "vjepa2": "V-JEPA 2 ViT-L (frozen)",
    "videomae": "VideoMAE V1 ViT-L (frozen)",
    "webdino": "Web-DINO ViT-L (frozen)",
    "caip_native_conditioned": "CAIP ViT-L, text-conditioned$^{*}$",
}
VISION_ORDER = ["caip_visual_only", "vjepa2", "videomae", "webdino"]
TEXT_ORDER = ["caip_native_conditioned"]


def num(x: str) -> str:
    v = float(x)
    s = f"{v:+.3f}" if v < 0 else f"{v:.3f}"
    return s.replace("-", "$-$").replace("+", "")


def ci(lo: str, hi: str) -> str:
    return f"[{num(lo)}, {num(hi)}]"


def main() -> None:
    rows = {r["encoder"]: r for r in csv.DictReader(SRC.open())}
    missing = [e for e in VISION_ORDER + TEXT_ORDER if e not in rows]
    if missing:
        raise KeyError(f"encoders missing from {SRC}: {missing}")
    const = {r["const_baseline_r2_at_compat"] for r in rows.values()}
    if len(const) != 1:
        raise ValueError(f"constant-baseline column is not unique: {const}")
    const_r2 = const.pop()

    def line(enc: str) -> str:
        r = rows[enc]
        return (f"{LABELS[enc]} & {num(r['r2_compat_200ep_mean'])} & "
                f"{num(r['r2_all26tasks_point'])} {ci(r['r2_all26tasks_ci95_lo'], r['r2_all26tasks_ci95_hi'])} & "
                f"{num(r['diff_vs_const_point'])} {ci(r['diff_vs_const_ci95_lo'], r['diff_vs_const_ci95_hi'])} \\\\")

    out = [
        "% Auto-generated by scripts/camera_ready/build_caip_table.py -- do not edit by hand.",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        " & $R^2$ (200 ep) & $R^2$ (26 tasks) [95\\% CI] & $R^2 -$ constant (26 tasks) [95\\% CI] \\\\",
        "\\midrule",
        *[line(e) for e in VISION_ORDER],
        f"Constant predictor & {num(const_r2)} & -- & -- \\\\",
        "\\midrule",
        *[line(e) for e in TEXT_ORDER],
        "\\bottomrule",
        "\\end{tabular}",
        "% $^{*}$ receives the LIBERO task description as text input; reported separately from the",
        "% vision-only rows and not included in any vision-only ranking.",
    ]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "caip_table.tex").write_text("\n".join(out) + "\n")
    (OUT_DIR / "caip_table.provenance.json").write_text(json.dumps({
        "script": str(Path(__file__).relative_to(REPO_ROOT)),
        "input": {"path": str(SRC.relative_to(REPO_ROOT)),
                  "sha256": hashlib.sha256(SRC.read_bytes()).hexdigest()},
    }, indent=2))
    print("\n".join(out))


if __name__ == "__main__":
    main()
